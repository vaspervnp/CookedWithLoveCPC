#!/usr/bin/env python3
"""HUD texts of one language (data/text/strings.tsv) -> asm:

  <font.asm>     the glyphs of the letters the texts use (tools/mkfont.py
                 LETTERS), to follow hud_font (base RAM); G_BASE + i
  <strings.asm>  txt_<id>: the glyph numbers of each text, #FF at the end;
                 those of the overlay (where: ovl) under ifdef OVERLAY, for
                 src/ovl/prep.asm to include

Digits, space and ':' are glyphs of the HUD font already. Accents are
dropped (capitals), Greek capitals shaped like Latin ones share their glyph.

Usage: text2asm.py <strings.tsv> <en|gr> <font.asm> <strings.asm>
"""

import sys
import unicodedata

from mkfont import DIGITS, LETTERS, base_glyphs, glyph, pack, plain_char


def plain(ch):
    return plain_char(ch)


def main():
    tsv, lang, font_out, str_out = sys.argv[1:5]
    rows = [l.rstrip("\n").split("\t") for l in open(tsv, encoding="utf-8")
            if l.strip() and not l.startswith("#")]
    col = rows[0].index(lang)
    where = rows[0].index("where")
    texts = [(r[0], r[col], r[where]) for r in rows[1:]]
    names = base_glyphs()[0]
    base = {k: names.index("G_" + k) for k in DIGITS}
    base[" "] = names.index("G_SPACE")
    base[":"] = names.index("G_COLON")
    used = []
    enc = []
    for tid, text, wh in texts:
        out = []
        for ch in text:
            if ch in base:
                out.append(base[ch])
                continue
            c = plain(ch)
            if c not in LETTERS:
                sys.exit(f"{tsv}: {tid}: no glyph for {ch!r}")
            if c not in used:
                used.append(c)
            out.append(len(names) + used.index(c))
        enc.append((tid, text, wh, out))
    with open(font_out, "w", encoding="utf-8") as f:
        f.write(f"; generated by tools/text2asm.py ({lang}): follows hud_font\n")
        for c in used:
            f.write("\tdb " + ",".join(f"#{b:02X}" for b in pack(glyph(LETTERS[c]))) + f"\t; {c}\n")
    with open(str_out, "w", encoding="utf-8") as f:
        f.write(f"; generated by tools/text2asm.py ({lang})\n")
        for wh, cond in (("game", "ifndef"), ("ovl", "ifdef")):
            f.write(f"\t{cond} OVERLAY\t\t; ({wh})\n")
            for tid, text, w, out in enc:
                if w == wh:
                    f.write(f"txt_{tid.lower()}:\t; {text}\n\tdb " + ",".join(map(str, out)) + ",#FF\n")
                    f.write(f"TXT_{tid}_LEN\tequ {len(out)}\n")
            f.write("\tendif\n")
    print(f"{lang}: {len(texts)} texts, {sum(len(o) for *_, o in enc)} chars, {len(used)} letters",
          file=sys.stderr)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Convert a sprite sheet PNG into Mode 0 span data for src/engine/sprite.asm.

The sheet holds frames of WxH pixels left to right, top to bottom. Pixels with
alpha < 128 are transparent (pen 0); opaque colours must be in the game palette
(opaque black is pen 14).

Frame format (one per frame, H lines):
    db start, nl, no, nr     ; first non-empty byte of the line, then counts of
                             ; masked / opaque / masked bytes (opaque = both
                             ; pixels non-transparent: copied without mask)
    db bytes...              ; nl+no+nr Mode 0 bytes

Output: an asm include with
    <prefix>_frames: dw frame0, frame1, ...   (frame pointer table)
    <prefix>_f<N>:   frame data

--mirror-from N appends horizontally mirrored copies of frames N..end (e.g.
the side view, to get the opposite side).
"""

import argparse
import sys

from PIL import Image

from png2cpc import to_pens
from cpc import mode0_byte


def frame_lines(rows):
    """Per line: (start, nl, no, nr, bytes)."""
    out = []
    w = len(rows[0])
    for r in rows:
        bs = [mode0_byte(r[x], r[x + 1]) for x in range(0, w, 2)]
        used = [i for i, x in enumerate(range(0, w, 2)) if r[x] or r[x + 1]]
        if not used:
            out.append((0, 0, 0, 0, []))
            continue
        s, e = used[0], used[-1] + 1
        opaque = [bool(r[2 * i] and r[2 * i + 1]) for i in range(s, e)]
        best, bl, i = (0, 0), 0, 0
        while i < len(opaque):          # longest run of opaque bytes
            if opaque[i]:
                j = i
                while j < len(opaque) and opaque[j]:
                    j += 1
                if j - i > best[1] - best[0]:
                    best = (i, j)
                i = j
            else:
                i += 1
        a, b = best
        if b - a < 2:
            a = b = 0
            out.append((s, e - s, 0, 0, bs[s:e]))
        else:
            out.append((s, a, b - a, (e - s) - b, bs[s:e]))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sheet")
    ap.add_argument("output")
    ap.add_argument("--prefix", required=True)
    ap.add_argument("--size", default="32x48")
    ap.add_argument("--frames", type=int, default=0, help="number of frames (default: all)")
    ap.add_argument("--mirror-from", type=int, default=-1)
    args = ap.parse_args()

    fw, fh = (int(v) for v in args.size.split("x"))
    img = Image.open(args.sheet).convert("RGBA")
    pens = to_pens(img, False, sprite=True)
    cols, nrows = img.width // fw, img.height // fh
    frames = []
    for fy in range(nrows):
        for fx in range(cols):
            rows = [pens[fy * fh + y][fx * fw:(fx + 1) * fw] for y in range(fh)]
            frames.append(rows)
    if args.frames:
        frames = frames[:args.frames]
    if args.mirror_from >= 0:
        frames += [[list(reversed(r)) for r in f] for f in frames[args.mirror_from:]]

    total = 0
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(f"; generated by tools/sprite2asm.py from {args.sheet}\n")
        f.write(f"{args.prefix}_frames:\n")
        for i in range(len(frames)):
            f.write(f"\tdw {args.prefix}_f{i}\n")
        for i, rows in enumerate(frames):
            f.write(f"{args.prefix}_f{i}:\n")
            for st, nl, no, nr, bs in frame_lines(rows):
                data = [st, nl, no, nr] + bs
                total += len(data)
                f.write("\tdb " + ",".join(f"#{b:02X}" for b in data) + "\n")
    print(f"{len(frames)} frames, {total} bytes", file=sys.stderr)


if __name__ == "__main__":
    main()

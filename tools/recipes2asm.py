#!/usr/bin/env python3
"""Recipes (data/recipes/recipes.tsv) -> the game's dish table.

Output (asm, bank 5):
  DISH_N        dishes of the first menu (menu 0), DISHES all of them
  dish_ticks    cooking time in game ticks per dish (word): 150 + 5 per
                minute on the site, so 15' is ~4.5 s, 80' ~11 s
  dish_price    price per dish (byte), by course
  dish_cost     the ingredients of a portion (byte): about 40% of the price
  dish_stn      the station of a dish (Medium): 0 stove (pot or pan), 1 oven
  dish_need     its ingredient groups (Hard): bits ING_* (V, M, G, D, P)
  dish_prep     minutes of the morning preparation per portion (byte): a
                tenth of the time on the site, at least 2
  (nothing for the overlay, src/ovl/prep.asm with -DOVERLAY=1: it has the
  game's symbols. The HUD icons: G_DISH0 + 2 * dish for the menu, by
  tools/mkfont.py; the later recipes' ones in build/recicons.asm. Bought
  in the evening, a recipe changes places with a dish of the menu in all
  these tables: src/game/menu.asm)

Usage: recipes2asm.py <recipes.tsv> <out.asm>
"""

import sys

PRICE = {"starter": 8, "main": 12, "side": 6, "sweet": 7}
COST = {"starter": 3, "main": 5, "side": 2, "sweet": 3}


def load(path):
    rows = [l.rstrip("\n").split("\t") for l in open(path, encoding="utf-8") if l.strip() and not l.startswith("#")]
    head, rows = rows[0], rows[1:]
    return [dict(zip(head, r)) for r in rows]


def main():
    dishes = load(sys.argv[1])
    first = [d for d in dishes if d["menu"] == "0"]
    order = first + [d for d in dishes if d["menu"] != "0"]
    with open(sys.argv[2], "w") as f:
        f.write(f"; generated by tools/recipes2asm.py from {sys.argv[1]}\n")
        f.write("\tifndef OVERLAY\n")
        f.write(f"DISH_N\tequ {len(first)}\t; the first menu\nDISHES\tequ {len(order)}\n")
        f.write("dish_ticks:\n")
        for d in order:
            f.write(f"\tdw {150 + 5 * int(d['time'])}\t; {d['id']}: {d['en']}\n")
        f.write("dish_price:\n\tdb " + ",".join(str(PRICE[d["course"]]) for d in order) + "\n")
        f.write("dish_cost:\n\tdb " + ",".join(str(COST[d["course"]]) for d in order) + "\n")
        f.write("".join(f"ING_{g}\tequ {i}\t; ingredient group (bit of dish_need)\n" for i, g in enumerate("VMGDP")))
        f.write("ING_N\tequ 5\nING_COLD\tequ %01010\t; M, D: in the fridges\n")
        f.write("dish_need:\n\tdb " + ",".join(str(sum(1 << "VMGDP".index(g) for g in d["groups"])) for d in order) + "\n")
        f.write("dish_stn:\t; where Liberty cooks it (Medium): 0 stove (pot, pan), 1 oven\n\tdb "
                + ",".join("1" if "oven" in d["stations"] else "0" for d in order) + "\n")
        f.write("dish_prep:\t; minutes of the morning per portion (src/ovl/prep.asm)\n\tdb " + ",".join(str(max(2, (int(d["time"]) + 5) // 10)) for d in order) + "\n")
        f.write("\tendif\n")


if __name__ == "__main__":
    main()
